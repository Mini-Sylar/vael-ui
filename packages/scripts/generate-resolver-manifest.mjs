#!/usr/bin/env node
// Regenerates ui/src/resolver/generated/component-names.ts from the SAME
// hand-maintained COMPONENTS list generate-vapor.mjs uses — one list, two
// consumers, so vael-ui/resolver can never drift out of sync with what
// vael-ui actually exports.

import { writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { COMPONENTS } from './component-names.mjs'

const __dirname = dirname(fileURLToPath(import.meta.url))
const OUT_DIR = join(__dirname, '../ui/src/resolver/generated')
const OUT_FILE = join(OUT_DIR, 'component-names.ts')

mkdirSync(OUT_DIR, { recursive: true })

const sorted = [...COMPONENTS].sort()
const body = `// Generated by scripts/generate-resolver-manifest.mjs — do not edit by hand.
// Source of truth: packages/scripts/component-names.mjs.
export const COMPONENT_NAMES: ReadonlySet<string> = new Set(${JSON.stringify(sorted, null, 2)})
`

writeFileSync(OUT_FILE, body)
console.log(`generated ${OUT_FILE} (${sorted.length} component names)`)
